// Renders building, icon, and effect sprites from the Three.js models in models/ with headless
// Chrome. AGENTS.md (Generated Assets) lists every model, its output, and its command.
//
//   cd tools/sprites && npm install
//   node render.mjs                     every model
//   node render.mjs --export            every model, exported into the mods
//   node render.mjs growth-facility     just these
//     [--out=dir] (default: out/) [--elevation=60] (camera degrees above the ground)
//     [--frames=n] (override the model's frame count) [--channel=chrome]
//     [--export] (also write the sheets and their util.sprite_load metadata into the mod, at the
//     model's `export` path prefix)
//
// For each model, writes into the output directory:
//   <name>-<layer>.png       one Factorio sheet per layer: main, shadow, mask-*, glow-*, and the model's
//                            own extra layers (see render.js)
//   <name>.json              each sheet's Factorio fields for `scale = 0.5`: width, height,
//                            frame_count, line_length, and shift in tiles
//   <name>-preview.html      animated day/night preview, with a variant picker, beside reference art
//   <name>-preview.png       a still of that preview
// Icon models (`type: "icon"`) instead write <name>.png, a 120x64 strip of 64, 32, 16, and 8 px
// renders (Factorio infers the custom mipmaps from the width), and <name>-preview.png showing it
// in inventory slots beside vanilla icons; --export copies the strip to the model's export path.
// FACTORIO_DATA overrides the Factorio data directory used for vanilla reference art.
import { chromium } from "playwright-core";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "../..");
const FACTORIO_DATA = process.env.FACTORIO_DATA ?? "/Applications/factorio.app/Contents/data";
// The renderer page is served from the repository root through request interception, so module
// imports work without a local web server.
const ORIGIN = "http://bte.local";
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".png": "image/png", ".json": "application/json" };

const args = process.argv.slice(2);
const opt = Object.fromEntries(args.filter((a) => a.startsWith("--")).map((a) => {
  const [key, value = "true"] = a.slice(2).split("=");
  return [key, value];
}));
const names = args.filter((a) => !a.startsWith("--"));
const models = names.length ? names : readdirSync(join(HERE, "models")).filter((f) => f.endsWith(".js")).map((f) => f.slice(0, -3)).sort();
const out = resolve(opt.out ?? join(HERE, "out"));
const number = (value) => (value === undefined ? undefined : Number(value));

/**
 * Reference art paths are `repo:<path>` or `factorio:<path>`. Each file is copied next to the
 * preview so the page loads everything from its own folder: embedded browsers such as VS Code's
 * refuse file:// images from outside the workspace.
 */
function copyReference(path) {
  const [scheme, rest] = path.split(/:(.*)/s);
  const base = { repo: REPO, factorio: FACTORIO_DATA }[scheme];
  if (!base) throw new Error(`unknown reference path ${path}`);
  const name = `${scheme}-${rest.replace(/[\\/]/g, "-")}`;
  mkdirSync(join(out, "refs"), { recursive: true });
  copyFileSync(join(base, rest), join(out, "refs", name));
  return `refs/${name}`;
}

/**
 * Copies each sheet into the mod as `<exportPath>-<layer>.png` plus the `.lua` metadata that
 * Factorio's util.sprite_load() reads (width, height, shift, line_length), the same pairing
 * vanilla Space Age graphics use. `exportPath` is the model's repository-relative path prefix.
 */
function exportSheets(name, exportPath, sheets) {
  if (!exportPath) throw new Error(`${name} has no export path`);
  const prefix = resolve(REPO, exportPath);
  if (!prefix.startsWith(REPO + sep)) throw new Error(`${name} export path leaves the repository`);
  mkdirSync(dirname(prefix), { recursive: true });
  for (const [layer, { dataURL, width, height, shift, line_length }] of Object.entries(sheets)) {
    writeFileSync(`${prefix}-${layer}.png`, Buffer.from(dataURL.split(",")[1], "base64"));
    writeFileSync(`${prefix}-${layer}.lua`, `-- Generated by tools/sprites/render.mjs from models/${name}.js; re-run it instead of editing.
return
{
  width = ${width},
  height = ${height},
  shift = {${shift[0]}, ${shift[1]}},
  line_length = ${line_length},
}
`);
    console.log(`exported ${relative(REPO, prefix)}-${layer}.png`);
  }
}

async function renderIcon(page, name) {
  const result = await page.evaluate(([model, elevation]) => window.renderIcon(model, { elevation }), [name, number(opt.elevation)]);
  const png = Buffer.from(result.icon.split(",")[1], "base64");
  writeFileSync(join(out, `${name}.png`), png);
  if ("export" in opt) {
    if (!result.exportPath) throw new Error(`${name} has no export path`);
    const target = resolve(REPO, result.exportPath);
    if (!target.startsWith(REPO + sep)) throw new Error(`${name} export path leaves the repository`);
    writeFileSync(target, png);
    console.log(`exported ${result.exportPath}`);
  }
  // Inventory-style comparison: each icon at 64 and 32 px in slot-coloured squares, zoomed 2x.
  const preview = await page.evaluate(async ([icon, refs]) => {
    const load = async (src) => {
      const image = new Image();
      image.src = src;
      await image.decode();
      return image;
    };
    const icons = [await load(icon), ...(await Promise.all(refs.map((r) => load(`/__factorio__/${r}`))))];
    const zoom = 2;
    const slot = 72;
    const canvas = document.createElement("canvas");
    canvas.width = icons.length * (slot + 40) * zoom;
    canvas.height = (slot + 44 + 8) * zoom;
    const ctx = canvas.getContext("2d");
    ctx.imageSmoothingEnabled = false;
    ctx.fillStyle = "#242324";
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    icons.forEach((image, i) => {
      const x = (i * (slot + 40) + 8) * zoom;
      for (const [size, y, box] of [[64, 8, slot], [32, slot + 12, 40]]) {
        ctx.fillStyle = "#8e8e8e";
        ctx.fillRect(x - zoom, y * zoom - zoom, (box + 2) * zoom, (box + 2) * zoom);
        ctx.fillStyle = "#3d3d3d";
        ctx.fillRect(x, y * zoom, box * zoom, box * zoom);
        const inset = ((box - size) / 2) * zoom;
        // The strip's mipmap of this size if it has one, otherwise its base level scaled.
        const base = image.height;
        const [from, span] = size === base ? [0, base] : size === base / 2 && image.width > base ? [base, size] : [0, base];
        ctx.imageSmoothingEnabled = span !== size;
        ctx.drawImage(image, from, 0, span, span, x + inset, y * zoom + inset, size * zoom, size * zoom);
      }
    });
    return canvas.toDataURL("image/png");
  }, [result.icon, result.references]);
  writeFileSync(join(out, `${name}-preview.png`), Buffer.from(preview.split(",")[1], "base64"));
}

const browser = await chromium.launch({ channel: opt.channel ?? "chrome", headless: true, args: ["--ignore-gpu-blocklist"] });
let failed = false;
try {
  const page = await browser.newPage();
  page.on("console", (message) => message.type() === "error" && console.error(`[page] ${message.text()}`));
  page.on("pageerror", (error) => console.error(`[page] ${error.message}`));
  await page.route(`${ORIGIN}/**`, async (route) => {
    // /__factorio__/<path> serves Factorio's data directory, for vanilla reference icons.
    const pathname = decodeURIComponent(new URL(route.request().url()).pathname);
    const [base, rest] = pathname.startsWith("/__factorio__/") ? [FACTORIO_DATA, pathname.slice(13)] : [REPO, pathname];
    const path = resolve(base, "." + rest);
    if (!path.startsWith(base + sep) || !existsSync(path)) return route.fulfill({ status: 404, body: "not found" });
    return route.fulfill({ status: 200, contentType: TYPES[extname(path)] ?? "application/octet-stream", body: readFileSync(path) });
  });
  await page.goto(`${ORIGIN}/tools/sprites/render.html`);
  await page.waitForFunction(() => window.rendererReady === true, null, { timeout: 30000 });

  mkdirSync(out, { recursive: true });
  for (const name of models) {
    const started = Date.now();
    if (await page.evaluate((model) => window.modelType(model), name) === "icon") {
      await renderIcon(page, name);
      console.log(`${name}: icon (${((Date.now() - started) / 1000).toFixed(1)} s)`);
      continue;
    }
    const { sheets, model } = await page.evaluate(([model, options]) => window.renderSprite(model, options),
      [name, { elevation: number(opt.elevation), frames: number(opt.frames) }]);
    const meta = { name, scale: 0.5, tiles: model.tiles, fps: model.fps, loop: model.loop, labels: model.labels, variants: model.variants, variantColors: model.variantColors, night: model.night, sheets: {} };
    for (const [layer, { dataURL, ...fields }] of Object.entries(sheets)) {
      writeFileSync(join(out, `${name}-${layer}.png`), Buffer.from(dataURL.split(",")[1], "base64"));
      meta.sheets[layer] = fields;
    }
    writeFileSync(join(out, `${name}.json`), JSON.stringify(meta, null, 2) + "\n");
    if ("export" in opt) exportSheets(name, model.exportPath, sheets);

    const references = model.references.map((ref) => ({
      ...ref, layers: ref.layers.map(({ file, ...layer }) => ({ ...layer, url: copyReference(file) }))
    }));
    // Space platform floor for the preview's "real background": 16 one-tile and 16 two-tile variants.
    const background = {
      small: copyReference("factorio:space-age/graphics/terrain/space-platform/space-platform-1x1.png"),
      large: copyReference("factorio:space-age/graphics/terrain/space-platform/space-platform-2x2.png"),
      variants: 16
    };
    writeFileSync(join(out, `${name}.meta.js`), `window.SPRITE_META = ${JSON.stringify({ ...meta, references, background }, null, 2)};\n`);
    const previewScript = relative(out, join(HERE, "preview.js")).split(sep).join("/");
    writeFileSync(join(out, `${name}-preview.html`), `<!doctype html>
<meta charset="utf-8">
<title>${name} sprite preview</title>
<style>
  body { margin: 0; background: #101113; color: #ddd; font: 14px system-ui, sans-serif; }
  header { display: flex; gap: 20px; align-items: center; padding: 10px 16px; background: #1d1f22; }
  h1 { font-size: 16px; margin: 0; }
  main { display: grid; grid-template-columns: repeat(2, max-content); gap: 12px; padding: 12px; }
  figure { margin: 0; }
  figcaption { padding: 4px 0; color: #aaa; }
  .error { color: #f66; padding: 16px; }
</style>
<body>
<script src="${name}.meta.js"></script>
<script src="${previewScript}"></script>
`);

    const preview = await browser.newPage({ viewport: { width: 1200, height: 800 } });
    await preview.goto(`${pathToFileURL(join(out, `${name}-preview.html`)).href}?frame=0`);
    await preview.waitForFunction(() => window.previewReady === true, null, { timeout: 30000 });
    await preview.screenshot({ path: join(out, `${name}-preview.png`), fullPage: true });
    await preview.close();

    // Effect models draw only extra layers and have no main sheet.
    const { width, height, frame_count, line_length } = meta.sheets.main ?? Object.values(meta.sheets)[0];
    console.log(`${name}: ${frame_count} frame(s) ${width}x${height}, ${line_length} per row, layers ${Object.keys(meta.sheets).join(", ")} ` +
      `(${((Date.now() - started) / 1000).toFixed(1)} s)`);
  }
} catch (error) {
  failed = true;
  console.error(error);
} finally {
  await browser.close();
}
process.exit(failed ? 1 : 0);
